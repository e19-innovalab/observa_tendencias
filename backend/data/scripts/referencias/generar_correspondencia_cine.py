"""Asigna a las carreras de Argentina, Chile y Uruguay su campo detallado CINE-F 2013.

    cd backend && .venv/bin/python ../data/scripts/referencias/generar_correspondencia_cine.py

Lee las carreras ya cargadas en la tabla graduates, les aplica reglas_carreras_cine.yaml (gana la
primera regla que coincide) y escribe config/reference/carreras_<país>_cine.yaml. Las ocupaciones
no se asignan acá: salen de la tabla común config/reference/cine_f_ciuo.yaml.

Controles (no escribe nada si alguno falla):
- cada código de las reglas existe en cine_f_2013.yaml;
- Chile publica el campo específico (3 dígitos) de cada carrera: se listan las carreras cuya regla
  asigna un campo de otro campo específico, para revisarlas (no bloquea).
Al final informa, por país, las carreras sin regla y la parte de los egresados con campo asignado.
"""
import json
import re
import sys
from pathlib import Path

import yaml

AQUI = Path(__file__).resolve().parent
BACKEND = AQUI.parents[2] / "backend"
sys.path.insert(0, str(BACKEND))

from sqlalchemy import func, select  # noqa: E402

from app.core.database import SessionLocal  # noqa: E402
from app.datasets.profiles import normalize_text  # noqa: E402
from app.models import Graduate  # noqa: E402

REFERENCIA = BACKEND / "config" / "reference"
# País -> perfil de archivo oficial y niveles que se usan (los mismos de las correspondencias
# anteriores por país).
PAISES = {
    "CHL": {"perfil": "mifuturo_titulados", "niveles": ["Pregrado"]},
    "ARG": {"perfil": "arg_egresados_universitarios", "niveles": ["Grado", "Pregrado"]},
    "URY": {"perfil": "mec_uy_egresados_grado", "niveles": ["Grado"]},
}
# Nombres de campo específico de Mi Futuro que no coinciden textualmente con CINE-F 2013.
ALIAS_ESPECIFICO = {
    "matematicas y estadisticas": "054",
    "servicios de seguridad": "103",
    "servicios de transportes": "104",
    "industria y produccion": "072",
    "ciencias naturales, matematicas y estadisticas sin mayor definicion": "05",
}
ENCABEZADO = """\
# Careers of {pais} -> CINE-F 2013 detailed field (config/reference/cine_f_2013.yaml). Their
# graduates reach CIUO-08 occupations through the table shared by the three countries,
# config/reference/cine_f_ciuo.yaml ("tecnico" codes for technical careers).
#
# GENERATED by data/scripts/referencias/generar_correspondencia_cine.py from the rules in
# data/scripts/referencias/reglas_carreras_cine.yaml (first matching rule wins). To change a
# career, edit the rules and run the script again rather than editing this file.
# STATUS: draft, NOT REVIEWED. cine: null = generic career (no field, no occupation).
# Each line ends with the career's graduates in the loaded years and the field's name.

"""


def main() -> int:
    archivo = yaml.safe_load((AQUI / "reglas_carreras_cine.yaml").read_text(encoding="utf-8"))
    cine = yaml.safe_load((REFERENCIA / "cine_f_2013.yaml").read_text(encoding="utf-8"))
    detallado = cine["detailed"]
    especifico = {normalize_text(v): k for k, v in cine["narrow"].items()} | ALIAS_ESPECIFICO
    desconocidos = sorted({r["cine"] for r in archivo["reglas"] if r["cine"]} - set(detallado))
    if desconocidos:
        print(f"Códigos que no están en cine_f_2013.yaml: {desconocidos}. No se escribió nada.")
        return 1
    reglas = [(re.compile(r["patron"]), r) for r in archivo["reglas"]]
    tecnico = re.compile(archivo["patron_tecnico"])
    revisada = bool(archivo.get("revisada"))

    with SessionLocal() as s:
        for pais, conf in PAISES.items():
            filas = s.execute(
                select(Graduate.career_key, func.min(Graduate.career), func.min(Graduate.field_subarea),
                       func.sum(Graduate.graduates))
                .where(Graduate.country_iso3 == pais, Graduate.level.in_(conf["niveles"]))
                .group_by(Graduate.career_key)).all()
            if not filas:
                print(f"{pais}: no hay egresados cargados; se omite.")
                continue
            filas.sort(key=lambda f: (-f[3], f[0]))
            lineas, sin_regla, distintos = [], [], []
            total = asignado = 0.0
            for clave, nombre, subarea, egresados in filas:
                nombre_norm = normalize_text(nombre)
                regla = next((r for patron, r in reglas if patron.search(nombre_norm)), None)
                codigo = regla["cine"] if regla else None
                total += egresados
                if regla is None:
                    sin_regla.append((nombre, egresados))
                elif codigo:
                    asignado += egresados
                    oficial = especifico.get(normalize_text(subarea or ""))
                    if oficial and not codigo.startswith(oficial):
                        distintos.append(f"{nombre} → {codigo} (Mi Futuro: {subarea})")
                valor = {"cine": codigo}
                if codigo and tecnico.search(nombre_norm):
                    valor["tecnico"] = True
                etiqueta = "SIN REGLA" if regla is None else (
                    detallado[codigo] if codigo else "genérica")
                lineas.append(f"  {json.dumps(nombre, ensure_ascii=False)}: "
                              f"{json.dumps(valor, ensure_ascii=False)}  # {int(egresados)} · {etiqueta}")
            niveles_tec = archivo.get("niveles_tecnicos", {}).get(pais, [])
            cuerpo = (ENCABEZADO.format(pais=pais)
                      + f"reviewed: {str(revisada).lower()}\ncountry: {pais}\n"
                      f"source_profile: {conf['perfil']}\nlevels: {json.dumps(conf['niveles'])}\n"
                      "via: reference/cine_f_ciuo.yaml\n"
                      f"technical_levels: {json.dumps(niveles_tec)}\n\ncareers:\n"
                      + "\n".join(lineas) + "\n")
            salida = REFERENCIA / f"carreras_{pais.lower()}_cine.yaml"
            salida.write_text(cuerpo, encoding="utf-8")
            print(f"{pais}: {len(filas)} carreras · {len(filas) - len(sin_regla)} con regla · "
                  f"egresados con campo CINE-F: {asignado / total:.1%} · escrito {salida.name}")
            for nombre, egresados in sin_regla:
                print(f"    sin regla: {nombre} ({int(egresados)})")
            for d in distintos:
                print(f"    revisar: {d}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
