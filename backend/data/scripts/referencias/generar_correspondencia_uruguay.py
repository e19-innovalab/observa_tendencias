"""Genera la correspondencia carrera → ocupación de Uruguay a partir de reglas.

    cd backend/backend && .venv/bin/python ../data/scripts/referencias/generar_correspondencia_uruguay.py

Lee las carreras de Uruguay ya cargadas en la tabla graduates (fuente mec_uruguay, Anuario
Estadístico de Educación), les aplica reglas_carreras_uruguay.yaml (gana la primera regla que
coincide) y escribe config/reference/carreras_uruguay_ciuo.yaml con una fila por carrera, ordenadas
por cantidad de egresados. Las carreras sin regla quedan como genéricas (sin ocupación) y se
listan al final, para agregarles una regla. No escribe nada si una regla usa un código CIUO que no
está en el universo de ocupaciones.
"""
import json
import re
import sys
from pathlib import Path

import yaml

AQUI = Path(__file__).resolve().parent
BACKEND = AQUI.parents[2] / "backend"
sys.path.insert(0, str(BACKEND))

from sqlalchemy import func, select  # noqa: E402

from app.core.config_files import catalog  # noqa: E402
from app.core.database import SessionLocal  # noqa: E402
from app.datasets.profiles import normalize_text  # noqa: E402
from app.models import Graduate  # noqa: E402

PAIS = "URY"
SALIDA = BACKEND / "config" / "reference" / "carreras_uruguay_ciuo.yaml"
ENCABEZADO = """\
# Crosswalk: Uruguayan university degree programs (Anuario Estadístico de Educación, MEC) →
# ISCO-08 / CIUO-08 unit groups they mainly train for. Used for the supply side of skill gaps.
#
# GENERATED by data/scripts/referencias/generar_correspondencia_uruguay.py from the rules in
# data/scripts/referencias/reglas_carreras_uruguay.yaml (first matching rule wins). To change a
# program, edit the rules and run the script again rather than editing this file.
#
# STATUS: draft, NOT REVIEWED (reviewed: false). There is no official crosswalk. Same criteria as
# the Chilean and Argentine ones (data/scripts/referencias/README.md, section 5).
#
# Programs are the names as published (the same program appears with several names: "Licenciatura
# en ..." and "Licenciado en ..."); each line ends with its graduates 2020-2024 and the rule used.

"""


def main() -> int:
    archivo = yaml.safe_load((AQUI / "reglas_carreras_uruguay.yaml").read_text(encoding="utf-8"))
    reglas, revisada = archivo["reglas"], bool(archivo.get("revisada"))
    universo = {o.occupation_code for o in catalog().occupations}
    desconocidos = sorted({f"{c:0>4}" for r in reglas for c in r["codes"]} - universo)
    if desconocidos:
        print(f"Códigos fuera del universo CIUO: {desconocidos}. No se escribió nada.")
        return 1
    compiladas = [(re.compile(r["patron"]), r) for r in reglas]

    with SessionLocal() as s:
        filas = s.execute(select(Graduate.career_key, func.min(Graduate.career),
                                 func.sum(Graduate.graduates))
                          .where(Graduate.country_iso3 == PAIS)
                          .group_by(Graduate.career_key)).all()
    if not filas:
        print("No hay egresados de Uruguay cargados: correr antes la fuente mec_uruguay.")
        return 1
    filas.sort(key=lambda f: (-f[2], f[0]))

    lineas, sin_regla = [], []
    total = mapeado = 0.0
    for clave, nombre, egresados in filas:
        regla = next((r for patron, r in compiladas if patron.search(normalize_text(clave))), None)
        total += egresados
        codes = [] if regla is None else [int(c) for c in regla["codes"]]
        if regla is None:
            sin_regla.append((nombre, egresados))
        elif codes:
            mapeado += egresados
        etiqueta = "SIN REGLA" if regla is None else (regla.get("nota") or regla["patron"])
        # codes below 1000 are quoted: a bare 0110 would be read as an octal number
        lista = "[" + ", ".join(f'"{c:04d}"' if c < 1000 else str(c) for c in codes) + "]"
        lineas.append(f"  {json.dumps(nombre, ensure_ascii=False)}: "
                      f"{lista}  # {int(egresados)} · {etiqueta}")

    cuerpo = (ENCABEZADO + f"reviewed: {str(revisada).lower()}\ncountry: {PAIS}\n"
              "source_profile: mec_uy_egresados_grado\nlevels: [Grado]\n\ncareers:\n"
              + "\n".join(lineas) + "\n")
    SALIDA.write_text(cuerpo, encoding="utf-8")
    print(f"{len(filas)} carreras · {len(filas) - len(sin_regla)} con regla · "
          f"egresados con ocupación: {mapeado / total:.1%} · escrito {SALIDA.name}")
    for nombre, egresados in sin_regla:
        print(f"  sin regla: {nombre} ({int(egresados)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
